import Foundation

/// What the graph knows about one repo, for `AGENTS.md` (defined here so ScopeTasks does not depend on ScopeGraph).
public struct RepoContextSummary: Sendable, Equatable, Hashable {
    /// Repo path relative to the scope root (`"."` for a repo scope) — the graph key.
    public var path: String
    public var purpose: String?
    public var stack: [String]
    public var setup: String?
    public var test: String?
    /// Run before the sandbox is removed (archive, close); not shown to agents.
    public var teardown: String?

    public init(path: String, purpose: String? = nil, stack: [String] = [], setup: String? = nil, test: String? = nil,
                teardown: String? = nil) {
        self.path = path
        self.purpose = purpose
        self.stack = stack
        self.setup = setup
        self.test = test
        self.teardown = teardown
    }
}

/// Renders the files Scope projects into a task root (spec §4.6): `AGENTS.md` and the
/// `<slug>.code-workspace` multi-root file. Pure functions, testable without git.
public enum TaskProjection {
    /// Marker on the first line of a generated `AGENTS.md`, so a user-authored file is recognisable.
    public static let generatedMarker = "<!-- generated by Scope; edits are overwritten when the task changes -->"

    /// `AGENTS.md` content.
    ///
    /// - Parameters:
    ///   - task: the task; its active repos are listed with their sandbox paths.
    ///   - otherRepos: relative paths of the scope's other repos.
    ///   - scopeName: display name of the scope.
    ///   - scopeContext: what the owner wrote about the scope (`ScopeDeclaration.context`), quoted as it is.
    ///   - repoSummaries: graph cards (purpose / stack / setup / test), keyed by relative path; missing entries fall back to names only.
    public static func agentsMarkdown(
        task: TaskRecord, otherRepos: [String], scopeName: String, scopeContext: String? = nil,
        repoSummaries: [RepoContextSummary] = []
    ) -> String {
        let summaries = Dictionary(repoSummaries.map { (TaskRepo.normalize($0.path), $0) }, uniquingKeysWith: { first, _ in first })
        var lines: [String] = [generatedMarker, "# Task: \(task.name)", ""]
        lines.append("- Scope: \(scopeName)")
        lines.append("- Branch: `\(task.branch)`")
        lines.append("- Task root: `\(task.root)`")
        if let issue = task.issue {
            lines.append("- Issue: \(issue.label) \(issue.url.absoluteString) — the pull request that closes it must reference it (`Closes \(issue.label)` in its body)")
        }
        if let deliverable = task.deliverable {
            lines.append("- Deliverable: `\(deliverable)` (in the task root or a sandbox) — write the result of the task there; Scope keeps it when the task is archived")
        }
        lines.append("")
        if let prompt = task.prompt?.trimmingCharacters(in: .whitespacesAndNewlines), !prompt.isEmpty {
            lines.append("## Goal")
            lines.append("")
            lines.append(prompt)
            lines.append("")
        }
        if let mission = task.mission {
            lines.append("## Mission")
            lines.append("")
            lines += missionProtocol(task: task, mission: mission)
            lines.append("")
        }
        if let context = scopeContext?.trimmingCharacters(in: .whitespacesAndNewlines), !context.isEmpty {
            lines.append("## About \(scopeName)")
            lines.append("")
            lines.append(context)
            lines.append("")
        }
        lines.append("## Repositories of this task")
        lines.append("")
        let active = task.activeRepos
        if active.isEmpty {
            lines.append("_No repository yet._")
        }
        for repo in active {
            let name = repo.isScopeRoot ? scopeName : repo.repoRelativePath
            lines.append("- **\(name)** — sandbox: `\(repo.sandboxPath)` (branch `\(repo.branch)`)")
            if let summary = summaries[repo.repoRelativePath] {
                if let purpose = summary.purpose { lines.append("  - Purpose: \(purpose)") }
                if !summary.stack.isEmpty { lines.append("  - Stack: \(summary.stack.joined(separator: ", "))") }
                if let setup = summary.setup { lines.append("  - Setup: `\(setup)`") }
                if let test = summary.test { lines.append("  - Test: `\(test)`") }
            }
        }
        lines.append("")
        let others = otherRepos.filter { path in !active.contains { $0.repoRelativePath == path } }.sorted()
        if !others.isEmpty {
            lines.append("## Other repositories of the scope")
            lines.append("")
            lines.append("Not part of this task. Ask before adding one to the task.")
            lines.append("")
            for path in others {
                if let purpose = summaries[path]?.purpose {
                    lines.append("- **\(path)** — \(purpose)")
                } else {
                    lines.append("- \(path)")
                }
            }
            lines.append("")
        }
        lines.append("## Rules")
        lines.append("")
        lines.append("- Work only inside the sandboxes listed above.")
        lines.append("- Never modify the base checkouts under `\(task.scopeRoot)`.")
        lines.append("- Stay on branch `\(task.branch)`; do not switch branches or create new ones.")
        lines.append("- Commit as you go; the user reviews and pushes from Scope.")
        lines.append("")
        return lines.joined(separator: "\n")
    }

    /// What a mission's agent is told (spec §4.3): the goal is reached through milestones, one child task at a time,
    /// each validated before the next opens. Scope keeps the list and runs the validation; the agent plans.
    static func missionProtocol(task: TaskRecord, mission: Mission) -> [String] {
        var lines = [
            "This task is a **mission**: the goal above is too big for one task. You are its orchestrator.",
            "",
            #"1. Split the goal into milestones, in order, each small enough for one task and each with a **validation**: a shell command that proves it (the test suite, a build, `gh pr checks <branch>` for green checks). Register them: `scope task milestone add \#(task.slug) "<title>" --validate "<command>"`."#,
            #"2. Open **one milestone at a time** as a child task (`scope task new "<brief>" --topic "\#(task.topic ?? task.name)"`), with a complete brief. Wait for its thread (`scope thread wait`)."#,
            #"3. When the child reports, mark the milestone done and name the child: `scope task milestone done \#(task.slug) <n> --child <slug>`. Scope runs the validation in the child's sandbox: `validated` opens the next milestone; `failed` sends the log to the child's thread, which fixes, and you mark done again."#,
            #"4. Open the next milestone only once the previous one is validated. The mission is reached when every milestone is. Then report: what each milestone delivered, its pull request, what is left."#,
        ]
        if !mission.milestones.isEmpty {
            lines.append("")
            lines.append("Milestones so far (\(mission.caption)):")
            for (index, milestone) in mission.milestones.enumerated() {
                var line = "\(index + 1). [\(milestone.state.rawValue)] \(milestone.title)"
                if let validation = milestone.validation { line += " — validate: `\(validation)`" }
                lines.append(line)
            }
        }
        return lines
    }

    /// `<slug>.code-workspace` content: one folder per active sandbox, named after the repo.
    public static func workspaceJSON(task: TaskRecord) throws -> Data {
        struct Folder: Encodable { let name: String; let path: String }
        struct Workspace: Encodable { let folders: [Folder]; let settings: [String: String] }
        let folders = task.activeRepos.map { repo in
            Folder(name: repo.isScopeRoot ? task.slug : repo.repoRelativePath,
                   path: repo.isScopeRoot ? "." : repo.repoRelativePath)
        }
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]
        return try encoder.encode(Workspace(folders: folders, settings: [:]))
    }
}
